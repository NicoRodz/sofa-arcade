// Writes docs/refactor/depcruise-report.md: warnings per rule of .dependency-cruiser.cjs (all rules are "warn" until F6).
//   npm run deps:report
import { spawnSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '../..');
const DIRS = ['platform', 'games', 'apps', 'tools'];
const r = spawnSync('npx', ['depcruise', '--config', '.dependency-cruiser.cjs', ...DIRS, '--output-type', 'json'], {
  cwd: ROOT,
  encoding: 'utf8',
  maxBuffer: 1 << 28,
});
const json = JSON.parse(r.stdout) as {
  summary: { totalCruised: number; violations: { rule: { name: string; severity: string }; from: string; to: string }[] };
};
const sha = spawnSync('git', ['rev-parse', '--short', 'HEAD'], { cwd: ROOT, encoding: 'utf8' }).stdout.trim();
const RULES = [
  'no-cross-game',
  'platform-not-games',
  'only-apps-compose',
  'pure-sim',
  'pure-sim-node-core',
  'public-api',
  'no-circular',
  'no-test-in-prod',
];
const by = new Map<string, typeof json.summary.violations>(RULES.map((n) => [n, []]));
for (const v of json.summary.violations) by.get(v.rule.name)?.push(v);

const lines = [
  '# dependency-cruiser: warnings per rule',
  '',
  `Generated by \`npm run deps:report\` from commit ${sha} over ${json.summary.totalCruised} modules (${DIRS.join(', ')}). Every rule is severity \`warn\` until F6; this is the distance to the target tree, not a list of bugs.`,
  '',
  '| Rule | Warnings | Reads as |',
  '|---|---:|---|',
  ...RULES.map(
    (n) =>
      `| ${n} | ${by.get(n)!.length} | ${
        {
          'no-cross-game': 'games/X imports games/Y',
          'platform-not-games': 'platform/** imports a game or an app',
          'only-apps-compose': 'someone imports a main.ts',
          'pure-sim': 'platform/core or a game sim side imports phaser, ws, express or a screen/controller/server package',
          'pure-sim-node-core': 'platform/core or a game sim side imports a Node core module (node:*)',
          'public-api':
            'cross-package import that is not an index.ts (the F3 move keeps the old per-file subpaths of @party/shared as package exports)',
          'no-circular': 'import cycles (one row per module in a cycle)',
          'no-test-in-prod': 'production code imports a test file or test harness',
        }[n]
      } |`,
  ),
  '',
  `Total: ${json.summary.violations.length}.`,
  '',
];
for (const n of RULES) {
  const vs = by.get(n)!;
  if (!vs.length || n === 'public-api') continue;
  lines.push(
    `## ${n}`,
    '',
    ...vs.slice(0, 40).map((v) => `- \`${v.from}\` -> \`${v.to}\``),
    vs.length > 40 ? `- ... +${vs.length - 40} more` : '',
    '',
  );
}
const api = by.get('public-api')!;
const perTarget = new Map<string, number>();
for (const v of api) perTarget.set(v.to, (perTarget.get(v.to) ?? 0) + 1);
lines.push(
  '## public-api, by target',
  '',
  ...[...perTarget]
    .sort((a, b) => b[1] - a[1])
    .slice(0, 15)
    .map(([t, c]) => `- ${c} x \`${t}\``),
  '',
);
writeFileSync(resolve(ROOT, 'docs/refactor/depcruise-report.md'), lines.join('\n'));
console.log(Object.fromEntries([...by].map(([n, v]) => [n, v.length])));
